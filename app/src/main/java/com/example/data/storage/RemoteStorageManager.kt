package com.example.data.storage

import android.content.Context
import android.content.SharedPreferences
import com.example.data.model.PairedClient
import org.json.JSONArray
import org.json.JSONObject
import java.util.UUID

class RemoteStorageManager(private val context: Context) {

    private val prefs: SharedPreferences =
        context.getSharedPreferences(PREF_NAME, Context.MODE_PRIVATE)

    companion object {
        private const val PREF_NAME = "remote_control_storage_prefs"
        private const val KEY_PIN = "key_pin_code"
        private const val KEY_DEVICE_SECRET = "key_device_secret"
        private const val KEY_PAIRED_CLIENTS_JSON = "key_paired_clients_json"
        private const val KEY_CUSTOM_SERIAL = "key_custom_serial"
        private const val KEY_CUSTOM_MAC = "key_custom_mac"
        private const val KEY_ASSET_TAG = "key_asset_tag"
    }

    /**
     * Hardware asset customization and calibration for device administrators.
     */
    fun getCustomSerial(): String? = prefs.getString(KEY_CUSTOM_SERIAL, null)
    fun saveCustomSerial(serial: String?) {
        val s = serial?.trim()
        if (s.isNullOrBlank()) {
            prefs.edit().remove(KEY_CUSTOM_SERIAL).apply()
        } else {
            prefs.edit().putString(KEY_CUSTOM_SERIAL, s).apply()
        }
    }

    fun getCustomMac(): String? = prefs.getString(KEY_CUSTOM_MAC, null)
    fun saveCustomMac(mac: String?) {
        val m = mac?.trim()?.uppercase()
        if (m.isNullOrBlank()) {
            prefs.edit().remove(KEY_CUSTOM_MAC).apply()
        } else {
            prefs.edit().putString(KEY_CUSTOM_MAC, m).apply()
        }
    }

    fun getAssetTag(): String? = prefs.getString(KEY_ASSET_TAG, null)
    fun saveAssetTag(tag: String?) {
        val t = tag?.trim()
        if (t.isNullOrBlank()) {
            prefs.edit().remove(KEY_ASSET_TAG).apply()
        } else {
            prefs.edit().putString(KEY_ASSET_TAG, t).apply()
        }
    }

    /**
     * Get or initialize persistent 6-digit PIN code.
     * The PIN remains stable across app restarts unless explicitly changed or regenerated by user.
     */
    fun getPinCode(): String {
        var pin = prefs.getString(KEY_PIN, null)
        if (pin.isNullOrBlank()) {
            pin = generateRandomPin()
            savePinCode(pin)
        }
        return pin
    }

    fun savePinCode(pin: String) {
        prefs.edit().putString(KEY_PIN, pin.trim()).apply()
    }

    /**
     * Permanent device hardware/installation secret key
     */
    fun getDeviceSecret(): String {
        var secret = prefs.getString(KEY_DEVICE_SECRET, null)
        if (secret.isNullOrBlank()) {
            secret = UUID.randomUUID().toString().replace("-", "")
            prefs.edit().putString(KEY_DEVICE_SECRET, secret).apply()
        }
        return secret
    }

    /**
     * Load all persistent paired clients from SharedPreferences.
     * Ensures paired devices are NEVER lost when app is killed or cleared from background.
     */
    fun loadPairedClients(): Map<String, PairedClient> {
        val jsonStr = prefs.getString(KEY_PAIRED_CLIENTS_JSON, null) ?: return emptyMap()
        val result = mutableMapOf<String, PairedClient>()
        try {
            val jsonArray = JSONArray(jsonStr)
            for (i in 0 until jsonArray.length()) {
                val obj = jsonArray.getJSONObject(i)
                val token = obj.optString("token", "")
                if (token.isNotBlank()) {
                    val client = PairedClient(
                        token = token,
                        name = obj.optString("name", "Win11 控制台"),
                        ip = obj.optString("ip", ""),
                        pairedAt = obj.optLong("pairedAt", System.currentTimeMillis()),
                        lastActiveAt = obj.optLong("lastActiveAt", System.currentTimeMillis()),
                        remark = obj.optString("remark", ""),
                        clientSecret = obj.optString("clientSecret", "")
                    )
                    result[token] = client
                }
            }
        } catch (e: Exception) {
            e.printStackTrace()
        }
        return result
    }

    /**
     * Save all paired clients to persistent storage.
     */
    @Synchronized
    fun savePairedClients(clients: Collection<PairedClient>) {
        try {
            val jsonArray = JSONArray()
            for (client in clients) {
                val obj = JSONObject().apply {
                    put("token", client.token)
                    put("name", client.name)
                    put("ip", client.ip)
                    put("pairedAt", client.pairedAt)
                    put("lastActiveAt", client.lastActiveAt)
                    put("remark", client.remark)
                    put("clientSecret", client.clientSecret)
                }
                jsonArray.put(obj)
            }
            prefs.edit().putString(KEY_PAIRED_CLIENTS_JSON, jsonArray.toString()).apply()
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

    @Synchronized
    fun savePairedClient(client: PairedClient) {
        val current = loadPairedClients().toMutableMap()
        current[client.token] = client
        savePairedClients(current.values)
    }

    @Synchronized
    fun removePairedClient(token: String) {
        val current = loadPairedClients().toMutableMap()
        if (current.remove(token) != null) {
            savePairedClients(current.values)
        }
    }

    @Synchronized
    fun updateClientRemark(token: String, remark: String) {
        val current = loadPairedClients().toMutableMap()
        val client = current[token]
        if (client != null) {
            current[token] = client.copy(remark = remark)
            savePairedClients(current.values)
        }
    }

    private fun generateRandomPin(): String {
        return (100000..999999).random().toString()
    }
}
